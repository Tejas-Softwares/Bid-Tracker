// Builds the web app into public/: index.html, one script, one stylesheet (fonts inlined), favicon.
// Run with: npm run build   (Vercel runs this on every deploy)
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const root = path.dirname(new URL(import.meta.url).pathname);
const out = path.join(root, 'public');
const r = (p) => path.join(root, p);

// 1. logo as inline SVG for the app
const svg = (name) => fs.readFileSync(r(`brand/${name}`), 'utf8').replace('<svg ', '<svg role="img" aria-label="Tejas Group" ');
const brand = { mark: svg('tejas-mark.svg'), word: svg('tejas-wordmark.svg'), logo: svg('tejas-logo.svg') };
fs.writeFileSync(r('src/js/brand.gen.js'), '// Generated by build.mjs from brand/. Do not edit by hand.\nexport const BRAND = ' + JSON.stringify(brand) + ';\n');

// 2. script
const res = await build({ entryPoints: [r('src/js/main.js')], bundle: true, format: 'iife', target: ['chrome105', 'edge105', 'firefox110', 'safari16'], charset: 'utf8', legalComments: 'none', write: false, minifySyntax: true });
const js = res.outputFiles[0].text;

// 3. styles with the Source Sans 3 fonts inlined
const b64 = (p) => fs.readFileSync(r(p)).toString('base64');
const latin = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
const faces = [400, 600, 700].flatMap((w) => [
  `@font-face{font-family:'Source Sans 3';font-style:normal;font-weight:${w};font-display:swap;src:url(data:font/woff2;base64,${b64(`assets/fonts/source-sans-3-latin-${w}-normal.woff2`)}) format('woff2');unicode-range:${latin}}`,
  `@font-face{font-family:'Source Sans 3';font-style:normal;font-weight:${w};font-display:swap;src:url(data:font/woff2;base64,${b64(`assets/fonts/rupee-${w}.woff2`)}) format('woff2');unicode-range:U+20B9}`,
]);
const css = faces.join('\n') + '\n' + fs.readFileSync(r('src/styles.css'), 'utf8');

const hash = (s) => crypto.createHash('sha256').update(s).digest('hex').slice(0, 10);
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(path.join(out, 'assets'), { recursive: true });
const jsName = `assets/app-${hash(js)}.js`, cssName = `assets/app-${hash(css)}.css`;
fs.writeFileSync(path.join(out, jsName), js);
fs.writeFileSync(path.join(out, cssName), css);
fs.writeFileSync(path.join(out, 'favicon.svg'), fs.readFileSync(r('brand/tejas-mark.svg')));

fs.writeFileSync(path.join(out, 'index.html'), `<!doctype html>
<html lang="en-IN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="Tejas Group bid tracker: enquiries, tenders, offers and results in one place.">
<meta name="robots" content="noindex, nofollow">
<title>Tejas Bid Tracker</title>
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
<link rel="stylesheet" href="/${cssName}">
</head>
<body>
<noscript><div style="padding:40px;font-family:sans-serif">The Tejas Bid Tracker needs JavaScript turned on.</div></noscript>
<script src="/${jsName}" defer></script>
</body>
</html>
`);
fs.writeFileSync(path.join(out, 'robots.txt'), 'User-agent: *\nDisallow: /\n');
console.log(`public/ built: ${jsName} ${(js.length / 1024).toFixed(0)} KB, ${cssName} ${(css.length / 1024).toFixed(0)} KB`);
